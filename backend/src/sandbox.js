import Docker from 'dockerode';
import fs from 'node:fs/promises';
import path from 'node:path';

const docker = new Docker({ socketPath: '/var/run/docker.sock' });

export const CONTAINER_IMAGE = 'node:20-alpine';

// 服务器硬约束：沙箱配额
export const CONSTRAINT = {
  Memory: 256 * 1024 * 1024, // 256MB
  CpuQuota: 50000, // 半核（CpuPeriod=100000）
  CpuPeriod: 100000,
  PidsLimit: 100,
  NetworkMode: 'none',
  AutoRemove: true,
};

const EXTERNAL_HARD_TIMEOUT_MS = 120 * 1000;
const TAIL_LINES = 50;

function workspaceRoot() {
  return process.env.WORKSPACE_DIR
    ? path.resolve(process.env.WORKSPACE_DIR)
    : path.resolve(process.cwd(), '../workspace');
}

// 挂载源必须位于 workspace/session-<ts>/build 前缀下，防止把任意宿主目录挂进容器。
export function isBuildDirAllowed(buildDir) {
  const resolved = path.resolve(buildDir);
  const prefix = path.join(workspaceRoot(), 'build');
  return resolved === prefix || resolved.startsWith(prefix + path.sep);
}

export function validationScriptText() {
  return `// generated by NL2EARS build sandbox - static validation, then exits.
'use strict';
const fs = require('fs');
const path = require('path');
const http = require('http');
const os = require('os');
const { spawnSync } = require('child_process');

const ROOT = '/app';
const failures = [];
function report(msg) { console.error(msg); failures.push(msg); }

function checkSyntax(content) {
  const tmp = path.join(os.tmpdir(), 'chk-' + Math.random().toString(36).slice(2) + '.js');
  fs.writeFileSync(tmp, content);
  let r = spawnSync('node', ['--check', tmp], { encoding: 'utf8' });
  // 若普通脚本检查失败且内容含 import/export，改用模块方式再试一次
  if (r.status !== 0 && /\\bimport\\s|export\\s+(default|const|let|var|function|class|\\{|\\*)/.test(content)) {
    const tmpM = path.join(os.tmpdir(), 'chk-' + Math.random().toString(36).slice(2) + '.mjs');
    fs.writeFileSync(tmpM, content);
    const r2 = spawnSync('node', ['--input-type=module', '--check', tmpM], { encoding: 'utf8' });
    fs.unlinkSync(tmpM);
    if (r2.status === 0) { fs.unlinkSync(tmp); return null; }
    r = r2;
  }
  fs.unlinkSync(tmp);
  if (r.status !== 0) return r.stderr || 'syntax error';
  return null;
}

function walkJs(dir, out) {
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    const st = fs.statSync(p);
    if (st.isDirectory()) walkJs(p, out);
    else if (name.endsWith('.js')) out.push(p);
  }
}

// 1. index.html 必须存在
const entry = path.join(ROOT, 'index.html');
if (!fs.existsSync(entry)) {
  report('index.html 不存在');
  console.error('STATIC_SYNTAX_FAIL');
  process.exit(1);
}

const html = fs.readFileSync(entry, 'utf8');

// 2a. 校验所有 .js 文件
const jsFiles = [];
walkJs(ROOT, jsFiles);
for (const p of jsFiles) {
  const err = checkSyntax(fs.readFileSync(p, 'utf8'));
  if (err) { report('语法错误 ' + p); report(String(err).slice(0, 1500)); }
}

// 2b. 校验 index.html 内联 <script> 块
const inlineScripts = [];
const re = /<script\\b[^>]*>([\\s\\S]*?)<\\/script>/gi;
let m;
while ((m = re.exec(html))) {
  const body = m[1];
  if (body.trim() && !/<\\/script/i.test(body)) inlineScripts.push(body);
}
inlineScripts.forEach((body, i) => {
  const err = checkSyntax(body);
  if (err) { report('内联 <script> #' + (i + 1) + ' 语法错误'); report(String(err).slice(0, 1200)); }
});

if (failures.length) {
  console.error('STATIC_SYNTAX_FAIL');
  process.exit(1);
}

// 3. 静态服务可达性：node 内置 http 监听 127.0.0.1 随机端口，请求 /index.html 非空即通过
const server = http.createServer((req, res) => {
  const reqPath = decodeURIComponent((req.url || '/').split('?')[0]);
  let fp;
  try { fp = path.join(ROOT, reqPath === '/' ? '/index.html' : reqPath); } catch { res.writeHead(400); res.end(); return; }
  const rel = path.relative(ROOT, fp);
  if (rel.startsWith('..') || path.isAbsolute(rel)) { res.writeHead(404); res.end(); return; }
  fs.stat(fp, (e, st) => {
    if (e || !st.isFile()) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(fs.readFileSync(fp));
  });
});

server.listen(0, '127.0.0.1', () => {
  const port = server.address().port;
  const req = http.get({ host: '127.0.0.1', port, path: '/index.html', timeout: 5000 }, (res) => {
    let data = '';
    res.on('data', (c) => { data += c; });
    res.on('end', () => {
      server.close();
      if (data.length > 0) {
        console.log('VALIDATION_PASS');
        process.exit(0);
      }
      report('index.html 返回空内容');
      console.error('STATIC_SYNTAX_FAIL');
      process.exit(1);
    });
  });
  req.on('error', () => { server.close(); report('服务可达性检查失败'); console.error('STATIC_SYNTAX_FAIL'); process.exit(1); });
  req.on('timeout', () => { server.close(); report('服务可达性检查超时'); console.error('STATIC_SYNTAX_FAIL'); process.exit(1); });
});
`;
}

// 管理员手动预拉镜像（导出供部署脚本使用；禁止在请求路径上在线拉镜像）。
export async function pullTemplateImage() {
  const exists = await docker.getImage(CONTAINER_IMAGE).inspect().then(() => true).catch(() => false);
  if (exists) return true;
  console.log('[sandbox] 基础镜像不存在，请先执行 setup-build-env.sh 预拉镜像');
  return false;
}

function tailLines(text, n = TAIL_LINES) {
  if (!text) return '';
  const lines = text.split('\n');
  return lines.slice(-n).join('\n');
}

async function runContainerOnce(buildDir) {
  const container = await docker.createContainer({
    Image: CONTAINER_IMAGE,
    Cmd: ['node', '/app/_validate.cjs'],
    HostConfig: {
      Binds: [`${buildDir}:/app:ro`],
      AutoRemove: CONSTRAINT.AutoRemove,
      Memory: CONSTRAINT.Memory,
      CpuQuota: CONSTRAINT.CpuQuota,
      CpuPeriod: CONSTRAINT.CpuPeriod,
      PidsLimit: CONSTRAINT.PidsLimit,
      NetworkMode: CONSTRAINT.NetworkMode,
      ReadonlyRootfs: true,
    },
    Tty: false,
  });

  let stdout = '';
  let stderr = '';
  let exitCode = null;
  const startTime = Date.now();
  let timedOut = false;
  const timer = setTimeout(() => { timedOut = true; }, EXTERNAL_HARD_TIMEOUT_MS);

  try {
    const stream = await container.attach({ stream: true, stdout: true, stderr: true });
    stream.on('data', (chunk) => {
      const s = chunk.toString('utf8');
      stdout += s;
      stderr += s;
    });
    await container.start();
    const res = await container.wait();
    exitCode = res && typeof res.StatusCode === 'number' ? res.StatusCode : null;
  } catch (e) {
    stderr += `\n[container] ${e.message}`;
  } finally {
    clearTimeout(timer);
  }

  if (timedOut) {
    await container.kill().catch(() => {});
    return { exitCode: 124, timedOut: true, stdout, stderr };
  }
  return { exitCode, timedOut: false, stdout, stderr };
}

// —— 串行队列：同时最多 1 个沙箱在跑，其余排队 ——
const queue = [];
let running = false;

function drain() {
  if (running) return;
  const next = queue.shift();
  if (!next) return;
  running = true;
  next.task()
    .then((r) => { next.resolve(r); running = false; drain(); })
    .catch((e) => { next.reject(e); running = false; drain(); });
}

export function enqueueSandbox(task) {
  return new Promise((resolve, reject) => {
    queue.push({ task, resolve, reject });
    drain();
  });
}

export function queueStats() {
  return { running, queued: queue.length };
}

export async function runValidation(buildDir) {
  if (!isBuildDirAllowed(buildDir)) {
    return { passed: false, exitCode: 1, stdoutTail: '', stderrTail: '拒绝: buildDir 不在 workspace/session-*/build 前缀下', errorType: 'path' };
  }
  const scriptPath = path.join(buildDir, '_validate.cjs');
  try {
    await fs.writeFile(scriptPath, validationScriptText(), 'utf8');
  } catch (err) {
    return { passed: false, exitCode: 1, stdoutTail: '', stderrTail: '写验证脚本失败: ' + err.message, errorType: 'write' };
  }

  let raw;
  try {
    raw = await enqueueSandbox(() => runContainerOnce(buildDir));
  } catch (err) {
    raw = { exitCode: null, timedOut: false, stdout: '', stderr: '调度沙箱失败: ' + err.message };
  } finally {
    await fs.rm(scriptPath, { force: true }).catch(() => {});
  }

  const passed = !raw.timedOut && raw.exitCode === 0;
  const errorType = raw.timedOut ? 'timeout' : raw.exitCode === 0 ? null : 'runtime';
  return {
    passed,
    exitCode: raw.exitCode,
    stdoutTail: tailLines(raw.stdout),
    stderrTail: tailLines(raw.stderr),
    errorType,
  };
}